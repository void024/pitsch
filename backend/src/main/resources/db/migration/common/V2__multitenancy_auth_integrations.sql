    decided_at         TIMESTAMP(6) WITH TIME ZONE,
    executed_at        TIMESTAMP(6) WITH TIME ZONE,
    idempotency_key    VARCHAR(200) NOT NULL UNIQUE,
    error              VARCHAR(1000),
    created_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version            BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_approvals_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE
);
CREATE INDEX idx_approvals_org_status ON approvals (organization_id, status, created_at);
CREATE INDEX idx_approvals_workflow ON approvals (workflow_id);

CREATE TABLE external_operations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    idempotency_key VARCHAR(200) NOT NULL UNIQUE,
    operation_type  VARCHAR(40) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    external_id     VARCHAR(255),
    workflow_id     BIGINT,
    attempts        INTEGER NOT NULL DEFAULT 0,
    error           VARCHAR(1000),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_external_operations_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE
);

-- HTTP Idempotency-Key replay store
CREATE TABLE idempotency_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    idem_key        VARCHAR(100) NOT NULL,
    method          VARCHAR(10) NOT NULL,
    path            VARCHAR(300) NOT NULL,
    request_hash    VARCHAR(64) NOT NULL,
    response_status INTEGER,
    response_body   TEXT,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency_records UNIQUE (user_id, idem_key)
);

-- Inbound webhook de-duplication (Gmail Pub/Sub pushes, Stripe events)
CREATE TABLE inbound_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source      VARCHAR(20)  NOT NULL,
    event_id    VARCHAR(200) NOT NULL,
    received_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_inbound_events UNIQUE (source, event_id)
);

-- ---------------------------------------------------------------------------------------------
-- Usage metering and subscriptions
-- ---------------------------------------------------------------------------------------------
CREATE TABLE usage_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL,
    user_id         BIGINT,
    metric          VARCHAR(40) NOT NULL,
    quantity        BIGINT NOT NULL,
    period_month    VARCHAR(7) NOT NULL,
    workflow_id     BIGINT,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_usage_records_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE
);
CREATE INDEX idx_usage_org_metric_period ON usage_records (organization_id, metric, period_month);

CREATE TABLE subscriptions (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id          BIGINT NOT NULL UNIQUE,
    plan_code                VARCHAR(32) NOT NULL,
    status                   VARCHAR(20) NOT NULL,
    provider                 VARCHAR(20) NOT NULL,
    provider_customer_id     VARCHAR(100),
    provider_subscription_id VARCHAR(100),
    current_period_start     TIMESTAMP(6) WITH TIME ZONE,
    current_period_end       TIMESTAMP(6) WITH TIME ZONE,
    cancel_at_period_end     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at               TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_subscriptions_org FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_subscriptions_plan FOREIGN KEY (plan_code) REFERENCES plans (code)
);

