-- V2: multi-tenancy, sessions, integrations, jobs, audit, approvals, usage and billing foundation.
--
-- Written to run on PostgreSQL (production) and on H2 in PostgreSQL mode (tests): one column per
-- ALTER statement, no vendor-specific functions. Existing data is preserved and back-filled:
--   * every existing user gets a personal workspace (organization) and an OWNER membership;
--   * every tenant-owned row is assigned to its owner's workspace;
--   * drafts that were "sent" while integrations were simulated are re-labelled SIMULATED (honesty fix);
--   * existing users are treated as email-verified (they could not verify before).

